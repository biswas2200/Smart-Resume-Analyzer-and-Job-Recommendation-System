package com.resumeanalyser.resume;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import java.util.List;
import java.util.UUID;

/**
 * The structured data extracted from one {@link Resume} by the ML parsing
 * service -- name, contact details, skills, work history, and education.
 * There is exactly one of these per resume version (1:1). Mirrors the
 * ML service's {@code ResumeProfile}/{@code ExperienceEntry}/{@code EducationEntry}
 * Pydantic models field-for-field, so the two sides of the system agree on shape.
 */
@Entity
@Table(name = "parsed_profiles")
@Getter
@Setter
public class ParsedProfile {

    /** Primary key, generated by the database on insert. */
    @Id
    @GeneratedValue
    private UUID id;

    /** The resume version this profile was extracted from. */
    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "resume_id", nullable = false, unique = true)
    private Resume resume;

    /** Candidate's full name, as extracted by the parser. Empty string if not found. */
    @Column(nullable = false)
    private String name = "";

    /** Contact email, as extracted by the parser. Empty string if not found. */
    @Column(nullable = false)
    private String email = "";

    /** Contact phone number, as extracted by the parser. Empty string if not found. */
    @Column(nullable = false)
    private String phone = "";

    /** Raw skill names as extracted by the parser -- not yet normalized against the skill taxonomy. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false)
    private List<String> skills;

    /** Work history entries, in the order the parser found them. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false)
    private List<ExperienceEntry> experience;

    /** Education entries, in the order the parser found them. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false)
    private List<EducationEntry> education;

    /** ATS compatibility score earned, from the same ML analysis run that produced this profile. */
    @Column(name = "ats_score", nullable = false)
    private double atsScore;

    /** Maximum possible ATS score for {@link #atsScore} to be measured against. */
    @Column(name = "ats_max_score", nullable = false)
    private double atsMaxScore;

    /** Individual pass/fail ATS checks backing {@link #atsScore}. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "ats_checks", nullable = false)
    private List<AtsCheckEntry> atsChecks;

    /** LLM-generated coaching explanation of the ATS score, role matches, and skill gaps. */
    @Column(nullable = false, columnDefinition = "TEXT")
    private String explanation = "";

    /**
     * One entry in a candidate's work history.
     *
     * @param title        job title
     * @param organization employer name
     * @param duration     free-text duration as written on the resume (e.g. "2022-2024"),
     *                     deliberately not parsed into start/end dates
     * @param description  free-text description of the role
     */
    public record ExperienceEntry(String title, String organization, String duration, String description) {}

    /**
     * One entry in a candidate's education history.
     *
     * @param degree      degree name (e.g. "B.S. Computer Science")
     * @param institution school/university name
     * @param year        free-text graduation year as written on the resume
     */
    public record EducationEntry(String degree, String institution, String year) {}

    /**
     * One named pass/fail ATS check, mirroring the ML service's {@code AtsCheck}.
     *
     * @param name   the check's identifier (e.g. {@code "contact_email"})
     * @param passed whether the resume passed this check
     * @param detail human-readable detail explaining the result
     */
    public record AtsCheckEntry(String name, boolean passed, String detail) {}
}
